// Offline replay of the accepted fictional terminal result, NOT real web acceptance.
import { test, expect } from "@playwright/test";
import { createServerClient } from "@supabase/ssr";
import { readFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
test("accepted synthetic terminal result renders completely; edits and export send no additional AI request", async ({ page, context, baseURL, request }) => {
  const root = new URL("../", import.meta.url);
  const accepted = JSON.parse(await readFile(new URL(".local-diagnostics/rewrite-compatibility-20261025.json", root), "utf8"));
  const pair = JSON.parse(await readFile(new URL(".local-diagnostics/scan-rewrite-acceptance-20261025.json", root), "utf8"));
  expect(accepted).toMatchObject({ syntheticOnly: true, outcome: "accepted", inferenceRequests: 1 });
  expect(pair.syntheticOnly).toBe(true);
  const { cv, jd } = pair.source;
  const result = accepted.result;
  await request.post("http://127.0.0.1:4399/__fixture/reset");
  await page.route("**/*", route => [baseURL, "http://127.0.0.1:4399"].includes(new URL(route.request().url()).origin) ? route.continue() : route.abort());
  const auth = createServerClient("http://127.0.0.1:4399", "fictional-visual-key", { cookies: { getAll: () => [], setAll: async cookies => context.addCookies(cookies.map(({ name, value }) => ({ name, value, url: baseURL! }))) } });
  expect((await auth.auth.signInWithPassword({ email: "fictional@example.test", password: "Synthetic only" })).error).toBeNull();
  await page.route("**/api/cv-review/disclosure", route => route.fulfill({ json: { provider: "Anthropic (Claude)", purpose: "synthetic-compatibility", external: true } }));
  await page.route("**/api/cv-review/extract?*", route => route.fulfill({ json: { text: cv } }));
  let scans = 0, rewrites = 0;
  await page.route("**/api/cv-review/scan", route => { scans++; return route.fulfill({ json: pair.acceptedScan }); });
  await page.route("**/api/cv-review/rewrite", route => { rewrites++; return route.fulfill({ json: result }); });
  await page.addInitScript(() => {
    Object.defineProperty(navigator, "clipboard", { value: { writeText: async (text: string) => { (window as unknown as { copiedText: string }).copiedText = text; } } });
  });
  await page.goto("/app");
  await expect(page.getByRole("heading", { name: "Scan your CV", exact: true })).toBeVisible();
  await expect(page.locator(".op-sidebar nav a")).toHaveCount(3);
  for (const name of ["Scan CV", "Rewrite CV", "Saved CVs"]) await expect(page.locator(".op-sidebar nav").getByRole("link", { name, exact: true })).toBeVisible();
  await page.locator('input[type="file"]').setInputFiles({ name: "fictional.pdf", mimeType: "application/pdf", buffer: Buffer.from("Synthetic extraction only") });
  await page.getByLabel("Target job").fill(jd);
  await page.getByRole("button", { name: "Scan CV", exact: true }).click();
  await page.getByRole("link", { name: "Rewrite this CV", exact: true }).first().click();
  await page.getByLabel("How should we improve it?").fill("Make the Sales CV clearer and concise. Preserve all facts, dates, qualifications and the manager's attribution/negation. Do not invent metrics or experience.");
  await page.getByRole("button", { name: "Rewrite CV", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Your rewritten CV is ready", exact: true })).toBeVisible();
  expect([scans, rewrites]).toEqual([1, 1]);
  await page.getByRole("button", { name: "Edit complete CV", exact: true }).click();
  await expect(page.getByLabel("Complete CV text")).toHaveValue(result.document);
  for (const text of ["2023–2025", "Business diploma, 2023", "My manager negotiated supplier contracts, not me.", result.replacements[0].text]) await expect(page.getByLabel("Formatted CV")).toContainText(text);
  const edited = result.document + "\nManual edit retained — no AI.";
  await page.getByLabel("Complete CV text").fill(edited);
  await expect(page.getByLabel("Formatted CV")).toContainText("Manual edit retained — no AI.");
  await page.getByRole("button", { name: "Copy text", exact: true }).click();
  expect(await page.evaluate(() => (window as unknown as { copiedText: string }).copiedText)).toBe(edited);
  const download = page.waitForEvent("download");
  await page.getByRole("button", { name: "Download TXT", exact: true }).click();
  const saved = await download;
  expect(await readFile((await saved.path())!, "utf8")).toBe(edited);
  const printFrame = page.frameLocator('iframe[title="CV print document"]');
  await expect(printFrame.locator("main")).toContainText("Manual edit retained — no AI.");
  await page.getByRole("button", { name: "Print / Save as PDF", exact: true }).click();
  await expect(page.getByText(/Print requested\. Choose a printer/)).toBeVisible();
  expect([scans, rewrites]).toEqual([1, 1]);
  await page.screenshot({ path: fileURLToPath(new URL("file:///tmp/opencode/rewrite-compat-result-browser/accepted-edited.png")), fullPage: true });
});
